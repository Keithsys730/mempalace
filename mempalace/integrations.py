"""Integration helpers for injecting MemPalace context into AI agents and prompts."""

from typing import Dict, Any, Optional
import os
from pathlib import Path
from .core import MemoryPalace
from .models import ContextLevel


def get_default_store_dir(store_dir: Optional[str] = None) -> str:
    """Find default memory store dir via 4-tier resolution chain:
    1. Explicit argument (`store_dir`)
    2. MEMPALACE_STORE_DIR environment variable
    3. <repo_root>/data/memory_store (anchored to package root)
    4. CWD fallback: 'data/memory_store'
    """
    # Tier 1: Explicit argument
    if store_dir:
        return store_dir

    # Tier 2: Environment variable
    env_path = os.environ.get("MEMPALACE_STORE_DIR")
    if env_path and env_path.strip():
        return env_path.strip()

    # Tier 3: Package repo root
    repo_store = Path(__file__).resolve().parents[1] / "data" / "memory_store"
    if os.path.exists(str(repo_store)):
        return str(repo_store)

    # Tier 4: CWD fallback
    return "data/memory_store"


def format_prompt_header(
    level: ContextLevel = ContextLevel.L0,
    store_dir: Optional[str] = None,
    palace: Optional[MemoryPalace] = None
) -> str:
    """Generate a compact, token-efficient prompt header string for Agent system prompts.

    Args:
        level: ContextLevel tier (defaults to L0 for ultra-low token overhead, ~30-50 tokens).
        store_dir: Path to memory store directory.
        palace: Pre-instantiated MemoryPalace instance.

    Returns:
        String ready for injection into LLM system prompts.
    """
    target_store = get_default_store_dir(store_dir)
    mp = palace or MemoryPalace(store_dir=target_store)
    pkg = mp.get_tiered_context(level=level)

    if level == ContextLevel.L0:
        return (
            f"[MemPalace L0 Context: {pkg.get('summary')} | "
            f"Tip: {pkg.get('tip_decision', 'None')} | "
            f"HashTip: {pkg.get('latest_hash_prefix')}]"
        )
    elif level == ContextLevel.L1:
        rules_str = " | ".join(f"{r['rule_id']}: {r['description']}" for r in pkg.get("immutable_rules", [])[:3])
        tip_frame = pkg.get("active_decision_stack", [])[-1] if pkg.get("active_decision_stack") else None
        tip_str = f"{tip_frame['verdict']}: {tip_frame['topic']}" if tip_frame else "None"
        lineage = pkg.get("event_lineage", {})
        return (
            f"=== MemPalace L1 Active Context ===\n"
            f"* Invariants (L1): {rules_str}\n"
            f"* Active Decision Tip (L3): {tip_str}\n"
            f"* Dead Ends: {len(pkg.get('dead_ends_pool', []))} recorded\n"
            f"* Event Lineage: Seq #{lineage.get('current_seq', 0)} (Hash: {lineage.get('latest_hash', '')[:16]}...)\n"
            f"==================================="
        )
    else:  # L2
        import json
        return f"=== MemPalace L2 Raw Context ===\n{json.dumps(pkg, ensure_ascii=False, indent=2)}\n================================"


def build_handoff_envelope(
    store_dir: Optional[str] = None,
    palace: Optional[MemoryPalace] = None
) -> Dict[str, Any]:
    """Generate structured handoff package for agent-to-agent task delegation."""
    target_store = store_dir or get_default_store_dir()
    mp = palace or MemoryPalace(store_dir=target_store)
    return mp.get_tiered_context(level=ContextLevel.L1)


def handle_post_compact(
    text_or_prompt: str,
    level: ContextLevel = ContextLevel.L1,
    store_dir: Optional[str] = None,
    palace: Optional[MemoryPalace] = None
) -> str:
    """Recover and re-inject a pristine MemPalace hot-cache header into a prompt after context compaction.

    If an older MemPalace header exists, it is replaced with a fresh header reflecting
    the latest invariants and decision tip. If missing, the fresh header is prepended.

    Args:
        text_or_prompt: Original or compacted prompt text.
        level: ContextLevel to inject (default L1 for balanced invariants + decision tip).
        store_dir: Optional memory store directory path.
        palace: Optional pre-instantiated MemoryPalace instance.

    Returns:
        String with guaranteed fresh MemPalace hot-cache context at the top.
    """
    fresh_header = format_prompt_header(level=level, store_dir=store_dir, palace=palace)
    if not text_or_prompt or not text_or_prompt.strip():
        return fresh_header

    import re
    # Patterns matching L0, L1, or L2 headers generated by format_prompt_header
    header_patterns = [
        r"\[MemPalace L0 Context:.*?\| HashTip:[^\]]*\]\n*",
        r"=== MemPalace L1 Active Context ===[\s\S]*?={10,}\n*",
        r"=== MemPalace L2 Raw Context ===[\s\S]*?={10,}\n*"
    ]

    cleaned_text = text_or_prompt
    for pat in header_patterns:
        cleaned_text = re.sub(pat, "", cleaned_text).lstrip()

    if not cleaned_text:
        return fresh_header

    return f"{fresh_header}\n\n{cleaned_text}"


def reinject_hot_cache(
    messages: list[Dict[str, Any]],
    level: ContextLevel = ContextLevel.L1,
    store_dir: Optional[str] = None,
    palace: Optional[MemoryPalace] = None
) -> list[Dict[str, Any]]:
    """Re-inject hot cache context into a structured message list (for Chat API formats).

    Args:
        messages: List of message dictionaries with 'role' and 'content'.
        level: ContextLevel to inject.
        store_dir: Path to memory store directory.
        palace: Optional MemoryPalace instance.

    Returns:
        New message list with MemPalace context restored in the first appropriate message.
    """
    import copy
    msgs = copy.deepcopy(messages)

    if not msgs:
        header = format_prompt_header(level=level, store_dir=store_dir, palace=palace)
        return [{"role": "system", "content": header}]

    # Target the first system message if present, otherwise the first message
    target_idx = 0
    for idx, m in enumerate(msgs):
        if m.get("role") == "system":
            target_idx = idx
            break

    orig_content = msgs[target_idx].get("content", "")
    if isinstance(orig_content, str):
        msgs[target_idx]["content"] = handle_post_compact(
            orig_content,
            level=level,
            store_dir=store_dir,
            palace=palace
        )
    elif isinstance(orig_content, list):
        # Support multimodal / structured content block list (e.g. [{"type": "text", "text": "..."}])
        for block in orig_content:
            if isinstance(block, dict) and block.get("type") == "text" and "text" in block:
                block["text"] = handle_post_compact(
                    block["text"],
                    level=level,
                    store_dir=store_dir,
                    palace=palace
                )
                break
    return msgs

